import Foundation

/// 系统提示词。集中放「雀魂 / 日麻 场景知识」，让模型知道截图里哪块是什么。
///
/// 这份提示词是实测调出来的，不是拍脑袋写的：
/// - 早期版本要求模型「逐项读出画面所有信息（手牌/牌河/副露/宝牌/点数…）」，
///   结果模型陷入长篇推演，低思考档也要烧 6000+ 思考 token、19~87 秒。
/// - 现在只要求「读手牌 + 给一打」，输出字段收敛，同样的低思考档降到 30s，
///   关掉思考后 1.5s，而分析质量不降（实测能正确数出向听、有效牌枚数）。
enum PromptTemplate {

    static let defaultSystem = """
    你是日本立直麻将（雀魂 Mahjong Soul）的顶级牌手兼教练。

    用户消息里给出**本地识别**的当前局面：自家手牌（含摸牌标记「·摸」）、各家副露、各家牌河、宝牌。
    这些信息由像素级识别产出，可靠，直接采信。本次没有图片输入，不要试图读图。

    # 任务
    综合手牌的向听与打点、三家牌河与副露的危险信号，给出当前最优的一打。

    # 要求
    - 点数、场风、剩余牌数、立直状态等未提供时，在 reason/danger 里注明「场况信息有限」并保守判断；绝不编造。
    - 全部简体中文（牌名用记号），只输出一个 JSON 对象，不要 markdown 围栏、不要其它文字。

    # 牌名记法（严格遵守）
    万子 1m~9m，筒子 1p~9p，索子 1s~9s；字牌 1z 东、2z 南、3z 西、4z 北、5z 白、6z 发、7z 中；赤宝牌 0m/0p/0s。

    # 输出格式
    {
      "hand": ["1m", "2m", "3m"],
      "melds": [],
      "dora": ["7p"],
      "turn": "自己出牌",
      "recommended": {"tile": "5m", "action": "打", "confidence": "high"},
      "reason": "为什么打这张：向听数、有效牌、打点，要具体。",
      "danger": {"level": "低", "detail": "主要危险来自哪家、哪些牌危险"},
      "alternatives": [{"tile": "8p", "why": "另一种可接受的打法与取舍"}],
      "lesson": "一条可复用的牌理，帮助用户长期进步",
      "uncertain": []
    }

    - "hand"/"melds"/"dora" 原样回填用户消息给的牌，不要增删。
    - "recommended" 的 confidence 与 danger 的 level 用 high/medium/low。
    """

    /// 三麻补充：自动附加在用户消息里
    static let sanmaNote = """
    注意：这是【三人麻将】。牌山不含万子（1m~9m 全部不存在），只有筒子、索子和字牌；北是拔北牌。判断时不要因为「没有万子」而困惑，也不要把看不清的牌猜成万子。
    """

    // MARK: - 逐张识牌
    //
    // 独立于主分析的一次专用调用：把每张牌单独切出来送进去。
    // 实测（真实雀魂截图）：整屏交给模型时 14 张只能读对 1~4 张，
    // 逐张独立送能读对 8~12 张。

    /// 逐张识牌专用提示词。
    ///
    /// 实测（真实雀魂截图，同一副手牌，真值 14 张）：
    ///
    /// | 送图方式 | 思考 | 准确率 | 耗时 |
    /// |---|---|---|---|
    /// | 只送全图 | 关 | 7/14 | 1.8s |
    /// | 只送全图 | 开 | 张数错 | 89s |
    /// | 全图 + 手牌合成条 | 开 | 张数错 | 110s |
    /// | 14 张单牌图 | 关 | 10/14 | 0.7s |
    /// | 14 张单牌图 | 开 | 14/14 | 5.4s |
    /// | **全图 + 14 张单牌图** | **开** | **14/14** | **4.4s** |
    ///
    /// 三条结论：
    /// 1. **每张牌必须是独立图片** —— 一张图里塞 14 张牌，模型对每张只剩 1/14 的
    ///    图片预算，圆圈/竹节根本数不清。放大整图或裁剪放大都没用。
    /// 2. **在"每张独立"的前提下，开思考才有意义** —— 此时它要推理的是
    ///    "逐张核对 14 张图"，正是思考擅长的事，思考量只要几百 token、4 秒就够。
    ///    而在整屏/合成图下开思考，90~110 秒仍然是错的（信息本来就不够）。
    /// 3. **全图一起送**带来交叉验证：模型能对着全图确认手牌区范围与张数。
    static let handReaderSystem = """
    你是日本立直麻将（雀魂）的读牌员。

    用户会给你若干张图片：
    - 第 1 张是雀魂对局的**完整截图**。
    - 第 2 张起，是从第 1 张里裁出来的**玩家自己的手牌**，按从左到右排列，每张图正好一张牌。

    只做一件事：识别出玩家手牌。**不要做任何战术分析。**

    只输出一个 JSON 对象，不要任何别的文字、不要 markdown 围栏：
    {"hand":["1m","2m","3s"]}

    要点：
    - **以那些单牌图逐张为准**去认每一张牌。第 1 张全图用来确定手牌区的范围与张数，并做交叉核对。
    - 输出张数应当等于你收到的单牌图张数。对不上就再逐张核对一遍。
    - 筒子数清圆圈个数，索子数清竹节根数 —— 这是最容易错的地方，务必数准。
    - 字牌一共只有七种：東 南 西 北 白 發 中。

    # 自查规则
    读完**自查一遍就立刻输出**，不要反复重复核对，思考要简短。

    1. **手牌是从小到大排好序的**：先万子、再筒子、再索子，最后字牌；同花色按数字升序。
       把读到的序列看一遍 —— 如果某张牌破坏了升序，那它很可能读错了，重新数那一张。
       例：`...1p 2p 0p 4p...`（0p 夹在 2p 与 4p 之间）、`...7s 6s...`（逆序）都明显不对。
    2. ★ **最要紧的一条**：手牌里**有对子、有跳号**（例如 `6p 6p 8p`）是**完全正常**的。
       **绝对不要为了让手牌看起来更整齐、更像顺子，而改动你读到的数字。**
       宁可保留"多出来的对子 / 跳号"，也不要把 `6p 6p 8p` 抹平成 `5p 6p 7p`
       （实测这是最容易犯的错：把 `6p 6p 8p` 顺化成 `5p 6p 7p`）。
       你要报的是**图上画着什么**，不是"手牌应该长什么样"。
    3. **只有数字 5 有赤牌版本**（0m / 0p / 0s），而且赤牌是**整张牌面都偏红**。
       普通牌上的红色装饰不是赤牌 —— 例如**三筒中间那个红色的圆圈**、
       **六筒下面那几个红圈**，都仍然是原牌，不要读成 0p。
    4. **按形状数，不要凭感觉**：
       - 筒子 = 数圆圈个数：1筒 1 个、2筒 2 个、3筒 3 个、4筒 4 个（2×2）、
         6筒 6 个（2 列 × 3 行）、8筒 8 个（2 列 × 4 行）。红圈照样各算一个。
       - 索子 = 数竹节根数：2索 2 根、3索 3 根、4索 4 根（2×2）、
         6索 6 根（3 列 × 2 行）、8索 8 根、9索 9 根（3×3）。
         **5索**是"四角 4 根 + 中间 1 根"，而且中间那根的**上方有一个小圆点**——
         那个圆点是装饰，**不是竹节，不要数进去**（数进去就会变成 6 根）。
         每根竹节两端粗、中间有一道细腰，那仍然是**一根**竹节，不要当成两根。
    5. 某张单牌图如果是**空白的**（上面什么图案都没有），那一格输出 "?"。
       不要跳过、也不要猜一张牌出来。输出元素个数必须等于单牌图张数。

    牌名记法：
    万子 1m~9m，筒子 1p~9p，索子 1s~9s；
    字牌 1z 东、2z 南、3z 西、4z 北、5z 白、6z 发、7z 中；
    赤宝牌 0m / 0p / 0s。
    """

    static func handReaderUser(tileCount: Int) -> String {
        """
        第 1 张是雀魂对局完整截图。后面 \(tileCount) 张是从它里面裁出来的玩家手牌，从左到右排列，每张图正好一张牌。
        请只识别手牌，输出 \(tileCount) 个牌名的 JSON 对象。
        """
    }

    /// 指示牌 → 宝牌（下一张）。2026-10-10 修正：宝牌 = 指示牌下一张。
    ///   数牌 1→9→1 循环；风牌 東南西北 循环；三元 白發中 循环。
    static func doraOf(_ indicator: String) -> String? {
        guard indicator.count == 2 else { return nil }
        let rank = String(indicator.prefix(1))
        let suit = String(indicator.suffix(1))
        if suit == "z" {
            let next: [String: String] = ["1": "2", "2": "3", "3": "4",
                                          "4": "1", "5": "6", "6": "7", "7": "5"]
            return next[rank].map { $0 + "z" }
        }
        guard let n = Int(rank) else { return nil }
        return "\(n % 9 + 1)\(suit)"
    }

    /// 附加在用户消息末尾的指令。
    /// knownDora 传的是**已换算的宝牌**（不是指示牌）。
    static func userInstruction(isSanma: Bool, deep: Bool,
                               knownHand: [String]? = nil,
                               knownDora: [String]? = nil,
                               localFacts: [String] = []) -> String {
        var s = "当前局面如下，请给出最优的一打。"

        if let hand = knownHand, !hand.isEmpty {
            s += "\n\n【手牌（\(hand.count) 张）】\n" + hand.joined(separator: " ")
        }
        if let dora = knownDora, !dora.isEmpty {
            s += "\n\n【宝牌】\n" + dora.joined(separator: " ")
        }
        if !localFacts.isEmpty {
            s += "\n\n【牌河 / 副露】"
            for f in localFacts { s += "\n- " + f }
        }

        s += deep
            ? "\n\n请把向听数、有效牌枚数、打点与防守风险都算清楚再下结论。"
            : "\n\n请直接给结论，不要长篇推演。"
        // ★ 输出长度约束（2026-10-18，防截断/提速）：字段值有上限，模型就不会
        //   把 token 花在长篇大论上；JSON 必须完整（截断的 JSON 无法解析）。
        s += "\n\n【输出长度】reason ≤ 80 字，danger.detail ≤ 40 字，lesson ≤ 50 字，"
        s += "alternatives 最多 2 条、每条 why ≤ 30 字。必须输出完整合法的 JSON，不要截断。"
        if isSanma { s += "\n\n" + sanmaNote }
        return s
    }
}
